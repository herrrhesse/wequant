// The facts the page reads from the backend's schema snapshot: request models' defaults, the operations available,
// the panel fields an expression reads and the index codes a pool accepts. gen-types writes them to
// src/api/contract.gen.ts so the page carries these, not the whole snapshot; src/api/contract.test.ts checks the two
// still agree.
export function contractFacts(schema) {
  const defs = schema.$defs ?? {};
  const defaults = {};
  for (const [name, def] of Object.entries(defs)) {
    const props = Object.entries(def.properties ?? {}).filter(([, p]) => p && typeof p === "object" && "default" in p);
    if (props.length) defaults[name] = Object.fromEntries(props.map(([k, p]) => [k, p.default]));
  }
  return {
    MODEL_DEFAULTS: defaults,
    AVAILABLE_OPERATIONS: (schema.operations ?? []).filter((o) => o.available).map((o) => o.operation),
    PANEL_FIELDS: defs.BarsRequest?.properties?.fields?.items?.enum ?? [],
    POOL_INDEX_CODES: defs.PoolSpec?.properties?.index?.anyOf?.[0]?.enum ?? [],
  };
}

const DOCS = {
  MODEL_DEFAULTS: "Each model's field defaults (BacktestRequest.cash, .execution, ...), never written in the UI.",
  AVAILABLE_OPERATIONS: "The service operations that exist; planned ones have fixed models but no command yet.",
  PANEL_FIELDS: "The panel fields an expression can read, in the snapshot's order (BarsRequest.fields).",
  POOL_INDEX_CODES: "The index codes pool.index accepts, in the snapshot's order.",
};
const TYPES = {
  MODEL_DEFAULTS: "Record<string, Record<string, unknown>>",
  AVAILABLE_OPERATIONS: "readonly string[]",
  PANEL_FIELDS: "readonly string[]",
  POOL_INDEX_CODES: "readonly string[]",
};

/** The source of src/api/contract.gen.ts. */
export function contractModule(schema, from) {
  const facts = contractFacts(schema);
  const lines = [`/* Generated by scripts/gen-types.mjs from ${from}. Do not edit; run npm run gen:types. */`, ""];
  for (const [name, value] of Object.entries(facts)) lines.push(`/** ${DOCS[name]} */`, `export const ${name}: ${TYPES[name]} = ${JSON.stringify(value)};`, "");
  return lines.join("\n");
}
