// Generate src/api/types.gen.ts from the backend's schema snapshot (`wequant schema --json`).
// Usage: npm run gen:types [-- path/to/schema.json]; default: contract/service-models.schema.json.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(process.argv[2] ?? `${root}/contract/service-models.schema.json`);
const out = `${root}/src/api/types.gen.ts`;

const schema = JSON.parse(readFileSync(source, "utf8"));
const defs = schema.$defs ?? schema.definitions ?? {};
const names = Object.keys(defs).sort();
if (names.length === 0) throw new Error(`${source}: no $defs to generate types from`);

// One root that references every model, so each $def becomes an exported interface.
const wrapper = {
  title: "ServiceModels",
  type: "object",
  additionalProperties: false,
  properties: Object.fromEntries(names.map((name) => [name, { $ref: `#/$defs/${name}` }])),
  $defs: defs,
};

const banner = `/* Generated by scripts/gen-types.mjs from ${relative(root, source)}. Do not edit; run npm run gen:types. */`;
const ts = await compile(wrapper, "ServiceModels", {
  bannerComment: banner,
  additionalProperties: false,
  unreachableDefinitions: true,
  style: { singleQuote: false },
});
writeFileSync(out, ts);
console.log(`${relative(root, out)}: ${names.length} models from ${relative(root, source)}`);

// src/api/operations.gen.ts: every operation's route (method, path from the snapshot) and its request and result types.
const ops = schema.operations ?? [];
const opsOut = `${root}/src/api/operations.gen.ts`;
const lines = [
  `/* Generated by scripts/gen-types.mjs from ${relative(root, source)}. Do not edit; run npm run gen:types. */`,
  'import type * as M from "./types.gen";',
  "",
  "/** Each operation's request and result model. */",
  "export interface Operations {",
  ...ops.map((o) => `  ${o.operation}: { request: M.${o.request}; result: M.${o.result} };`),
  "}",
  "",
  "export type Operation = keyof Operations;",
  "",
  "/** Each operation's HTTP route, as `wequant serve` declares it in the snapshot. */",
  "export const ROUTES: Record<Operation, { method: string; path: string }> = {",
  ...ops.map((o) => `  ${o.operation}: { method: ${JSON.stringify(o.method)}, path: ${JSON.stringify(o.path)} },`),
  "};",
  "",
];
writeFileSync(opsOut, lines.join("\n"));
console.log(`${relative(root, opsOut)}: ${ops.length} operations`);
